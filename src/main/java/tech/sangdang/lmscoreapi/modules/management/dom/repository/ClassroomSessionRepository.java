package tech.sangdang.lmscoreapi.modules.management.dom.repository;

import java.time.LocalDate;
import java.util.List;
import java.util.UUID;
import org.jspecify.annotations.NonNull;
import org.springframework.data.jdbc.repository.query.Query;
import org.springframework.data.repository.query.Param;
import org.springframework.stereotype.Repository;
import tech.sangdang.lmscoreapi.common.persistence.BaseCommandRepository;
import tech.sangdang.lmscoreapi.common.persistence.BaseQueryRepository;
import tech.sangdang.lmscoreapi.modules.management.dom.ClassroomSession;

@Repository
public interface ClassroomSessionRepository
    extends BaseCommandRepository<ClassroomSession, UUID>,
        BaseQueryRepository<ClassroomSession, UUID> {

  /**
   * OPEN sessions generated by a recurrence on or after {@code cutoffDate}.
   *
   * @param generatedBy recurrence id
   * @param cutoffDate inclusive lower bound on session_date
   */
  @Query(
      """
      SELECT * FROM classroom_session
      WHERE generated_by = :generatedBy
        AND status = 'OPEN'
        AND session_date >= :cutoffDate
      """)
  List<ClassroomSession> findOpenByGeneratedByAndSessionDateGreaterThanEqual(
      @NonNull @Param("generatedBy") UUID generatedBy,
      @NonNull @Param("cutoffDate") LocalDate cutoffDate);
}
